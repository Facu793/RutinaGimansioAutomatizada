CREATE TABLE plantilla (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    objetivo VARCHAR(200) NOT NULL,
    observaciones VARCHAR(1000),
    activa BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE modulo_plantilla (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plantilla_id BIGINT NOT NULL,
    nombre VARCHAR(80) NOT NULL,
    orden INTEGER NOT NULL,
    rondas INTEGER NOT NULL,
    descanso_ejercicio_segundos INTEGER NOT NULL,
    descanso_ronda_segundos INTEGER NOT NULL,
    CONSTRAINT fk_modulo_plantilla FOREIGN KEY (plantilla_id) REFERENCES plantilla (id),
    CONSTRAINT chk_modulo_plantilla_rondas CHECK (rondas >= 1),
    CONSTRAINT chk_modulo_plantilla_descanso_ejercicio CHECK (descanso_ejercicio_segundos >= 0),
    CONSTRAINT chk_modulo_plantilla_descanso_ronda CHECK (descanso_ronda_segundos >= 0),
    CONSTRAINT chk_modulo_plantilla_orden CHECK (orden >= 1)
);

CREATE TABLE ejercicio_plantilla (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modulo_id BIGINT NOT NULL,
    ejercicio_id BIGINT NOT NULL,
    orden INTEGER NOT NULL,
    modalidad VARCHAR(20) NOT NULL,
    repeticiones INTEGER,
    duracion_segundos INTEGER,
    distancia NUMERIC(8, 2),
    unidad_distancia VARCHAR(20),
    porcentaje_rm NUMERIC(4, 1),
    CONSTRAINT fk_ejercicio_plantilla_modulo FOREIGN KEY (modulo_id) REFERENCES modulo_plantilla (id),
    CONSTRAINT fk_ejercicio_plantilla_ejercicio FOREIGN KEY (ejercicio_id) REFERENCES ejercicio (id),
    CONSTRAINT chk_ejercicio_plantilla_orden CHECK (orden >= 1),
    CONSTRAINT chk_ejercicio_plantilla_repeticiones CHECK (repeticiones IS NULL OR repeticiones >= 1),
    CONSTRAINT chk_ejercicio_plantilla_duracion CHECK (duracion_segundos IS NULL OR duracion_segundos >= 1),
    CONSTRAINT chk_ejercicio_plantilla_distancia CHECK (distancia IS NULL OR distancia > 0),
    CONSTRAINT chk_ejercicio_plantilla_porcentaje CHECK (
        porcentaje_rm IS NULL OR (porcentaje_rm >= 1 AND porcentaje_rm <= 100)
    )
);

CREATE INDEX idx_modulo_plantilla ON modulo_plantilla (plantilla_id);
CREATE INDEX idx_ejercicio_plantilla_modulo ON ejercicio_plantilla (modulo_id);
CREATE INDEX idx_ejercicio_plantilla_ejercicio ON ejercicio_plantilla (ejercicio_id);
