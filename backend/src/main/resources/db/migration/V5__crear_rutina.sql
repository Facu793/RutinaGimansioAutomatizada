CREATE TABLE rutina (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alumno_id BIGINT NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    objetivo VARCHAR(200) NOT NULL,
    fecha_creacion DATE NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    observaciones VARCHAR(1000),
    activa BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_rutina_alumno FOREIGN KEY (alumno_id) REFERENCES alumno (id),
    CONSTRAINT chk_rutina_fechas CHECK (fecha_fin >= fecha_inicio)
);

CREATE TABLE modulo_rutina (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rutina_id BIGINT NOT NULL,
    nombre VARCHAR(80) NOT NULL,
    orden INTEGER NOT NULL,
    rondas INTEGER NOT NULL,
    descanso_ejercicio_segundos INTEGER NOT NULL,
    descanso_ronda_segundos INTEGER NOT NULL,
    CONSTRAINT fk_modulo_rutina FOREIGN KEY (rutina_id) REFERENCES rutina (id),
    CONSTRAINT chk_modulo_rondas CHECK (rondas >= 1),
    CONSTRAINT chk_modulo_descanso_ejercicio CHECK (descanso_ejercicio_segundos >= 0),
    CONSTRAINT chk_modulo_descanso_ronda CHECK (descanso_ronda_segundos >= 0),
    CONSTRAINT chk_modulo_orden CHECK (orden >= 1)
);

CREATE TABLE ejercicio_rutina (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modulo_id BIGINT NOT NULL,
    ejercicio_id BIGINT NOT NULL,
    orden INTEGER NOT NULL,
    modalidad VARCHAR(20) NOT NULL,
    repeticiones INTEGER,
    duracion_segundos INTEGER,
    distancia NUMERIC(8, 2),
    unidad_distancia VARCHAR(20),
    porcentaje_rm NUMERIC(4, 1),
    peso_calculado NUMERIC(6, 2),
    CONSTRAINT fk_ejercicio_rutina_modulo FOREIGN KEY (modulo_id) REFERENCES modulo_rutina (id),
    CONSTRAINT fk_ejercicio_rutina_ejercicio FOREIGN KEY (ejercicio_id) REFERENCES ejercicio (id),
    CONSTRAINT chk_ejercicio_rutina_orden CHECK (orden >= 1),
    CONSTRAINT chk_ejercicio_rutina_repeticiones CHECK (repeticiones IS NULL OR repeticiones >= 1),
    CONSTRAINT chk_ejercicio_rutina_duracion CHECK (duracion_segundos IS NULL OR duracion_segundos >= 1),
    CONSTRAINT chk_ejercicio_rutina_distancia CHECK (distancia IS NULL OR distancia > 0),
    CONSTRAINT chk_ejercicio_rutina_porcentaje CHECK (
        porcentaje_rm IS NULL OR (porcentaje_rm >= 1 AND porcentaje_rm <= 100)
    )
);

CREATE INDEX idx_rutina_alumno ON rutina (alumno_id);
CREATE INDEX idx_modulo_rutina ON modulo_rutina (rutina_id);
CREATE INDEX idx_ejercicio_rutina_modulo ON ejercicio_rutina (modulo_id);
CREATE INDEX idx_ejercicio_rutina_ejercicio ON ejercicio_rutina (ejercicio_id);
