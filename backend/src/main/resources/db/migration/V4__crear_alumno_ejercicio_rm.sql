CREATE TABLE alumno_ejercicio_rm (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alumno_id BIGINT NOT NULL,
    ejercicio_id BIGINT NOT NULL,
    peso NUMERIC(6, 2) NOT NULL,
    actualizado_en TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_rm_alumno FOREIGN KEY (alumno_id) REFERENCES alumno (id),
    CONSTRAINT fk_rm_ejercicio FOREIGN KEY (ejercicio_id) REFERENCES ejercicio (id),
    CONSTRAINT uq_alumno_ejercicio_rm UNIQUE (alumno_id, ejercicio_id),
    CONSTRAINT chk_rm_peso CHECK (peso > 0 AND peso <= 9999.99)
);

CREATE INDEX idx_rm_alumno ON alumno_ejercicio_rm (alumno_id);
