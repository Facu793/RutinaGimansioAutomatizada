CREATE TABLE categoria_ejercicio (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(60) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE ejercicio (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    categoria_id BIGINT NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_ejercicio_categoria
        FOREIGN KEY (categoria_id) REFERENCES categoria_ejercicio (id)
);

CREATE INDEX idx_categoria_ejercicio_nombre ON categoria_ejercicio (nombre);
CREATE INDEX idx_categoria_ejercicio_activo ON categoria_ejercicio (activo);
CREATE INDEX idx_ejercicio_nombre ON ejercicio (nombre);
CREATE INDEX idx_ejercicio_categoria ON ejercicio (categoria_id);
CREATE INDEX idx_ejercicio_activo ON ejercicio (activo);

